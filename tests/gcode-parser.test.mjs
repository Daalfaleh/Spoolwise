import assert from "node:assert/strict";
import test from "node:test";
import { parse3mfBuffer, parseDurationSeconds, parseGcodeText } from "../utils/gcodeParser.js";

const encoder = new TextEncoder();

function storedZip(entries) {
  const localParts = [];
  const centralParts = [];
  let localOffset = 0;

  for (const [name, value] of entries) {
    const nameBytes = encoder.encode(name);
    const data = encoder.encode(value);
    const local = new Uint8Array(30 + nameBytes.length + data.length);
    const localView = new DataView(local.buffer);
    localView.setUint32(0, 0x04034b50, true);
    localView.setUint16(4, 20, true);
    localView.setUint32(18, data.length, true);
    localView.setUint32(22, data.length, true);
    localView.setUint16(26, nameBytes.length, true);
    local.set(nameBytes, 30);
    local.set(data, 30 + nameBytes.length);
    localParts.push(local);

    const central = new Uint8Array(46 + nameBytes.length);
    const centralView = new DataView(central.buffer);
    centralView.setUint32(0, 0x02014b50, true);
    centralView.setUint16(4, 20, true);
    centralView.setUint16(6, 20, true);
    centralView.setUint32(20, data.length, true);
    centralView.setUint32(24, data.length, true);
    centralView.setUint16(28, nameBytes.length, true);
    centralView.setUint32(42, localOffset, true);
    central.set(nameBytes, 46);
    centralParts.push(central);
    localOffset += local.length;
  }

  const centralSize = centralParts.reduce((sum, part) => sum + part.length, 0);
  const end = new Uint8Array(22);
  const endView = new DataView(end.buffer);
  endView.setUint32(0, 0x06054b50, true);
  endView.setUint16(8, entries.length, true);
  endView.setUint16(10, entries.length, true);
  endView.setUint32(12, centralSize, true);
  endView.setUint32(16, localOffset, true);

  const output = new Uint8Array(localOffset + centralSize + end.length);
  let offset = 0;
  for (const part of [...localParts, ...centralParts, end]) {
    output.set(part, offset);
    offset += part.length;
  }
  return output.buffer;
}

test("parses common duration formats", () => {
  assert.equal(parseDurationSeconds("1h 10m 56s"), 4256);
  assert.equal(parseDurationSeconds("01:10:56"), 4256);
  assert.equal(parseDurationSeconds("4256"), 4256);
});

test("extracts model weight, wipe-tower waste, and time from Prusa-style G-code", () => {
  const result = parseGcodeText(`
; generated by PrusaSlicer 2.9
; filament used [g] = 56.58
; total filament used [g] = 60.58
; total filament used for wipe tower [g] = 4.00
; estimated printing time (normal mode) = 1h 10m 56s
  `, { fileName: "part.gcode" });

  assert.equal(result.slicer, "PrusaSlicer");
  assert.equal(result.modelWeightGrams, 56.58);
  assert.equal(result.wasteWeightGrams, 4);
  assert.equal(result.totalWeightGrams, 60.58);
  assert.equal(result.durationSeconds, 4256);
});

test("reads sliced metadata from a stored 3MF archive", async () => {
  const archive = storedZip([
    ["[Content_Types].xml", "<Types />"],
    ["Metadata/plate_1.gcode", `; generated by OrcaSlicer\n; filament used [g] = 25.5\n; flush filament [g] = 2.5\n; model printing time = 3600`],
  ]);
  const result = await parse3mfBuffer(archive, { fileName: "plate.3mf" });

  assert.equal(result.slicer, "OrcaSlicer");
  assert.equal(result.modelWeightGrams, 23);
  assert.equal(result.wasteWeightGrams, 2.5);
  assert.equal(result.totalWeightGrams, 25.5);
  assert.equal(result.durationSeconds, 3600);
});

test("rejects an unsliced 3MF archive without metadata", async () => {
  const archive = storedZip([["3D/mesh.bin", "geometry"]]);
  await assert.rejects(parse3mfBuffer(archive), /No sliced G-code or slicer metadata/);
});

