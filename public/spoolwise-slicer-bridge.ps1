param(
  [Parameter(Mandatory = $true)][string]$Endpoint,
  [Parameter(Mandatory = $true)][string]$Token,
  [Parameter(ValueFromRemainingArguments = $true)][string[]]$RemainingArguments
)

$ErrorActionPreference = "Stop"

function ConvertTo-SpoolwiseSeconds([string]$DurationText) {
  $value = $DurationText.Trim()
  if ($value -match "^\d+$") { return [int]$value }

  $days = if ($value -match "(?i)(\d+)\s*d") { [int]$Matches[1] } else { 0 }
  $hours = if ($value -match "(?i)(\d+)\s*h") { [int]$Matches[1] } else { 0 }
  $minutes = if ($value -match "(?i)(\d+)\s*m") { [int]$Matches[1] } else { 0 }
  $seconds = if ($value -match "(?i)(\d+)\s*s") { [int]$Matches[1] } else { 0 }
  return $days * 86400 + $hours * 3600 + $minutes * 60 + $seconds
}

try {
  if (-not $RemainingArguments -or $RemainingArguments.Count -lt 1) {
    throw "The slicer did not provide a G-code file path."
  }

  $gcodePath = $RemainingArguments[-1]
  if (-not (Test-Path -LiteralPath $gcodePath -PathType Leaf)) {
    throw "G-code file was not found."
  }

  $head = Get-Content -LiteralPath $gcodePath -TotalCount 4000
  $tail = Get-Content -LiteralPath $gcodePath -Tail 4000
  $metadata = ($head + $tail) -join [Environment]::NewLine

  $slicer = "Unknown slicer"
  if ($metadata -match "(?im)^;\s*generated by\s+([^\r\n]+)") { $slicer = $Matches[1].Trim() }
  elseif ($metadata -match "(?im)^;GENERATOR.NAME:([^\r\n]+)") { $slicer = $Matches[1].Trim() }

  $durationSeconds = 0
  if ($metadata -match "(?im)^;\s*(?:model printing time|total estimated time|estimated printing time[^=]*)\s*=\s*([^\r\n]+)") {
    $durationSeconds = ConvertTo-SpoolwiseSeconds $Matches[1]
  } elseif ($metadata -match "(?im)^;TIME:\s*(\d+)") {
    $durationSeconds = [int]$Matches[1]
  }

  $filamentGrams = 0.0
  if ($metadata -match "(?im)^;\s*(?:total )?filament used \[g\]\s*=\s*([^\r\n]+)") {
    foreach ($number in [regex]::Matches($Matches[1], "\d+(?:\.\d+)?")) {
      $filamentGrams += [double]::Parse($number.Value, [Globalization.CultureInfo]::InvariantCulture)
    }
  } elseif ($metadata -match "(?im)^;\s*filament used\s*=\s*(\d+(?:\.\d+)?)g") {
    $filamentGrams = [double]::Parse($Matches[1], [Globalization.CultureInfo]::InvariantCulture)
  }

  $wasteGrams = 0.0
  if ($metadata -match "(?im)^;\s*(?:flush filament|wipe tower|purge waste) \[g\]\s*=\s*([^\r\n]+)") {
    foreach ($number in [regex]::Matches($Matches[1], "\d+(?:\.\d+)?")) {
      $wasteGrams += [double]::Parse($number.Value, [Globalization.CultureInfo]::InvariantCulture)
    }
  }

  $printerName = $env:SLIC3R_PRINTER_SETTINGS_ID
  if (-not $printerName) { $printerName = $env:SLIC3R_PRINTER_MODEL }
  if (-not $printerName) { $printerName = "" }

  $payload = @{
    fileName = [IO.Path]::GetFileName($gcodePath)
    slicer = $slicer
    printerName = $printerName
    durationSeconds = $durationSeconds
    filamentGrams = [math]::Round($filamentGrams, 3)
    wasteGrams = [math]::Round($wasteGrams, 3)
  } | ConvertTo-Json -Compress

  Invoke-RestMethod -Uri $Endpoint -Method Post -Headers @{ Authorization = "Bearer $Token" } -ContentType "application/json" -Body $payload | Out-Null
  Write-Host "Spoolwise received the print estimate."
  exit 0
} catch {
  # Never block the slicer from exporting a print because the optional quote sync failed.
  Write-Warning "Spoolwise sync skipped: $($_.Exception.Message)"
  exit 0
}
